# 1-28 - февраль (32-59).
# 1-31 - март (60-90). (8) выходной. Номер 67
# 1-30 - апрель (91-120).
# 1-31 - май (121-151). (8) рабочий, (10, 11) выходной. Номер 128. Номер 130, 131
# 1-30 - июнь (152-181).
# 1-31 - июль (182-212).
# 1-31 - август (213-243).
# 1-30 - сентябрь (244-273).
# 1-31 - октябрь (274-304).
# 1-30 - ноябрь (305-334).
# 1-31 - декабрь (335-365).

def get_day_type(day):
    if not isinstance(day, int) or day <= 0 or day > 365:
        return
    elif day in [1, 7, 67, 130, 131]: # праздничные дни, которые не являются субботами и воскресеньями
        return "day off"
    elif day == 128: # перенос субботы на рабочий день
        return "workday"
    elif (day - 2) % 7 == 0 or (day - 3) % 7 == 0: # субботы и воскресенья
        return "day off"
    else:
        return "workday"
    
day = get_day_type(1)
print(day)

day = get_day_type(5)
print(day)

day = get_day_type(400)
print(day)
